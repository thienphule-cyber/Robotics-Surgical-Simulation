"""Shared, thread-safe system state used by the dashboard.

The simulation (main thread) writes into SystemState; the REST API and the
WebSocket hub (other threads) read from it. The dashboard never touches the
robot directly: user commands are queued here and the main loop decides what
to do with them.

SIMULATION ONLY: all patient data (including the vital signs) belongs to a
fixed mannequin and is generated by a small random-walk model.
"""

from __future__ import annotations

import dataclasses
import math
import queue
import random
import threading
import time
from collections import deque
from dataclasses import dataclass, field
from enum import Enum

import numpy as np

JOINT_NAMES = ["shoulder_pan", "shoulder_lift", "elbow",
            "wrist_1", "wrist_2", "wrist_3"]

LOG_LEVELS = ("debug", "info", "warning", "error")
_LEVEL_RANK = {name: i for i, name in enumerate(LOG_LEVELS)}


class Phase(str, Enum):
    """Procedure phases (same order as the overall workflow)."""
    IDLE = "idle"
    INITIALIZING = "initializing"
    PLANNING = "planning"
    VISION_INIT = "vision_init"
    POSITIONING = "positioning"
    SERVOING = "servoing"
    EVALUATION = "evaluation"
    COMPLETED = "completed"
    ABORTED = "aborted"


# The surgical region cannot be changed while the robot is moving.
ACTIVE_PHASES = (Phase.POSITIONING.value, Phase.SERVOING.value)

# Adjustable parameters: name -> (min, max, default)
CONFIG_SPEC = {
    "ibvs_gain": (0.05, 2.0, 0.6),
    "ibvs_tol_px": (0.5, 10.0, 1.5),
    "tcp_speed_max": (0.01, 0.5, 0.25),
    "qdot_max": (0.1, 2.0, 1.0),
    "warn_distance": (0.01, 0.2, 0.05),
}

# Every command that can be put in the queue (REST exposes only a subset).
COMMANDS = ("start", "pause", "resume", "stop", "estop", "reset_estop",
            "reset", "start_recording", "stop_recording", "select_region")

# Simulated vitals: name -> (baseline, noise step, min, max)
_VITAL_SPEC = {
    "heart_rate_bpm": (72.0, 0.6, 50.0, 120.0),
    "spo2_percent": (98.0, 0.1, 94.0, 100.0),
    "systolic_mmhg": (120.0, 0.8, 100.0, 140.0),
    "diastolic_mmhg": (80.0, 0.5, 60.0, 90.0),
    "resp_rate_bpm": (14.0, 0.2, 10.0, 20.0),
}


def to_jsonable(obj):
    """Convert numpy / enum / dataclass values into plain JSON types.

    NaN and infinity become None (they are not valid JSON).
    """
    if obj is None:
        return None
    if isinstance(obj, Enum):                       # before str (Phase is a str)
        return to_jsonable(obj.value)
    if isinstance(obj, (str, bool, np.bool_)):
        return obj if isinstance(obj, str) else bool(obj)
    if isinstance(obj, (int, np.integer)):
        return int(obj)
    if isinstance(obj, (float, np.floating)):
        f = float(obj)
        return f if math.isfinite(f) else None
    if isinstance(obj, np.ndarray):
        return to_jsonable(obj.tolist())
    if dataclasses.is_dataclass(obj) and not isinstance(obj, type):
        return to_jsonable(dataclasses.asdict(obj))
    if isinstance(obj, dict):
        return {str(k): to_jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple, set, deque)):
        return [to_jsonable(v) for v in obj]
    return str(obj)


@dataclass
class PatientState:
    patient_id: str = "MANNEQUIN-01"
    description: str = "Fixed surgical mannequin (simulation only)"
    posture: str = "supine"
    selected_region: str = "abdomen"
    available_regions: list = field(default_factory=lambda: ["abdomen", "chest"])
    site_position: list | None = None          # [x, y, z] in the world frame
    vitals_simulated: bool = True
    vitals: dict = field(default_factory=lambda: {
        k: spec[0] for k, spec in _VITAL_SPEC.items()})


class SystemState:
    def __init__(self, regions=None, default_region: str = "abdomen",
                max_logs: int = 500, seed: int | None = None):
        self._lock = threading.RLock()
        self._rng = random.Random(seed)
        self._commands = queue.Queue()

        self.version = 0
        self.updated_at = time.time()

        regions = list(regions) if regions else ["abdomen", "chest"]
        self.patient = PatientState(selected_region=default_region,
                                    available_regions=regions)

        self._status = {"phase": Phase.IDLE.value, "message": "",
                        "running": False, "paused": False, "recording": False,
                        "started_at": None, "finished_at": None}
        self.robot = {"joint_names": JOINT_NAMES, "q": None, "q_deg": None,
                    "qdot": None, "tcp_position": None, "sim_time": 0.0}
        self.vision = {"camera": "eye-in-hand", "current_features": None,
                    "desired_features": None, "error_px": None,
                    "n_features": 0, "status": "idle", "fps": None}
        self.safety = {"state": "ok", "estop": False, "violation_count": 0,
                    "min_clearance": None, "violations": []}
        self.performance = {}
        self.config = {k: spec[2] for k, spec in CONFIG_SPEC.items()}
        self.config_version = 0

        self.logs = deque(maxlen=max_logs)
        self._log_id = 0

    # ------------------------------------------------------------------
    def _touch(self):
        self.version += 1
        self.updated_at = time.time()

    # ------------------------------------------------------------------
    # Robot / vision / safety / performance updates (called by the sim)
    # ------------------------------------------------------------------
    def update_robot(self, q, tcp_position=None, t=None, qdot=None):
        with self._lock:
            q = np.asarray(q, dtype=float)
            self.robot["q"] = q.tolist()
            self.robot["q_deg"] = np.rad2deg(q).tolist()
            if tcp_position is not None:
                self.robot["tcp_position"] = np.asarray(tcp_position, dtype=float).tolist()
            if qdot is not None:
                self.robot["qdot"] = np.asarray(qdot, dtype=float).tolist()
            if t is not None:
                self.robot["sim_time"] = float(t)
            self._touch()

    def update_vision(self, uv=None, desired_uv=None, error_px=None,
                    n_features=None, status=None, fps=None, camera=None):
        with self._lock:
            if uv is not None:
                self.vision["current_features"] = np.asarray(uv, dtype=float).tolist()
            if desired_uv is not None:
                self.vision["desired_features"] = np.asarray(desired_uv, dtype=float).tolist()
            if error_px is not None:
                self.vision["error_px"] = float(error_px)
            if n_features is not None:
                self.vision["n_features"] = int(n_features)
            if status is not None:
                self.vision["status"] = str(status)
            if fps is not None:
                self.vision["fps"] = float(fps)
            if camera is not None:
                self.vision["camera"] = str(camera)
            self._touch()

    def update_safety(self, state: str, estop: bool = False,
                    violation_count: int = 0, min_clearance=None,
                    violations=None):
        with self._lock:
            previous = self.safety["state"]
            self.safety.update({
                "state": str(state),
                "estop": bool(estop),
                "violation_count": int(violation_count),
                "min_clearance": None if min_clearance is None else float(min_clearance),
                "violations": list(violations or []),
            })
            if state != previous and state in ("blocked", "estop"):
                detail = "; ".join(self.safety["violations"]) or "no details"
                self.log(f"Safety state -> {state}: {detail}",
                        level="error" if state == "estop" else "warning",
                        source="safety")
            self._touch()

    def update_performance(self, **metrics):
        with self._lock:
            self.performance.update(metrics)
            self._touch()

    # Convenience adapters for the objects of the control package -------
    def update_from_motion(self, motion_state: dict):
        """Use the dict returned by MotionController.get_state()."""
        self.update_robot(q=motion_state["q"],
                        tcp_position=motion_state.get("tcp_position"),
                        t=motion_state.get("t"))

    def update_from_safety_monitor(self, monitor, report=None):
        """Use a SafetyMonitor and (optionally) its latest SafetyReport."""
        if report is not None:
            state = report.state.value
        else:
            state = "estop" if monitor.estopped else "ok"
        self.update_safety(
            state=state,
            estop=monitor.estopped,
            violation_count=monitor.violation_count,
            min_clearance=getattr(report, "min_clearance", None),
            violations=getattr(report, "violations", None),
        )

    def update_from_ibvs(self, result, uv=None, desired_uv=None):
        """Use an IBVSResult."""
        self.update_vision(uv=uv, desired_uv=desired_uv,
                        error_px=result.error_px,
                        n_features=result.n_features,
                        status=result.status)

    # ------------------------------------------------------------------
    # Procedure status
    # ------------------------------------------------------------------
    @property
    def phase(self) -> str:
        with self._lock:
            return self._status["phase"]

    def set_phase(self, phase, message: str = ""):
        phase = Phase(phase).value
        with self._lock:
            now = time.time()
            if phase != Phase.IDLE.value and self._status["started_at"] is None:
                self._status["started_at"] = now
            if phase in (Phase.COMPLETED.value, Phase.ABORTED.value):
                self._status["finished_at"] = now
            self._status["phase"] = phase
            self._status["message"] = message
            self.log(f"Phase -> {phase}" + (f": {message}" if message else ""),
                    source="procedure")
            self._touch()

    def set_flags(self, running=None, paused=None, recording=None):
        with self._lock:
            if running is not None:
                self._status["running"] = bool(running)
            if paused is not None:
                self._status["paused"] = bool(paused)
            if recording is not None:
                self._status["recording"] = bool(recording)
            self._touch()

    def reset_procedure(self):
        """Back to idle with a clean timer (does not clear logs)."""
        with self._lock:
            self._status.update({"phase": Phase.IDLE.value, "message": "",
                                "running": False, "paused": False,
                                "started_at": None, "finished_at": None})
            self.performance = {}
            self._touch()

    # ------------------------------------------------------------------
    # Patient
    # ------------------------------------------------------------------
    def set_region(self, region: str, site_position=None):
        with self._lock:
            if region not in self.patient.available_regions:
                raise ValueError(f"Unknown region '{region}'")
            self.patient.selected_region = region
            if site_position is not None:
                self.patient.site_position = np.asarray(site_position, dtype=float).tolist()
            self.log(f"Surgical region set to '{region}'", source="patient")
            self._touch()

    def tick_vitals(self):
        """Advance the simulated mannequin vitals (small random walk)."""
        with self._lock:
            for name, (base, step, lo, hi) in _VITAL_SPEC.items():
                v = self.patient.vitals[name]
                v += 0.1 * (base - v) + self._rng.gauss(0.0, step)
                self.patient.vitals[name] = round(min(max(v, lo), hi), 1)

    # ------------------------------------------------------------------
    # Logs
    # ------------------------------------------------------------------
    def log(self, message: str, level: str = "info", source: str = "system") -> int:
        if level not in LOG_LEVELS:
            raise ValueError(f"level must be one of {LOG_LEVELS}")
        with self._lock:
            self._log_id += 1
            self.logs.append({"id": self._log_id, "time": time.time(),
                            "level": level, "source": source,
                            "message": str(message)})
            return self._log_id

    @property
    def last_log_id(self) -> int:
        with self._lock:
            return self._log_id

    def logs_since(self, last_id: int) -> list:
        with self._lock:
            return [dict(e) for e in self.logs if e["id"] > last_id]

    def recent_logs(self, limit: int = 100, level: str | None = None) -> list:
        """Latest log entries; `level` filters by minimum severity."""
        with self._lock:
            entries = list(self.logs)
        if level is not None:
            rank = _LEVEL_RANK[level]
            entries = [e for e in entries if _LEVEL_RANK[e["level"]] >= rank]
        return [dict(e) for e in entries[-limit:]]

    # ------------------------------------------------------------------
    # Configuration (REST can change it, the simulation reads it)
    # ------------------------------------------------------------------
    def get_config(self) -> dict:
        with self._lock:
            return dict(self.config)

    def set_config(self, updates: dict):
        """Validate and apply parameter changes (all or nothing)."""
        clean = {}
        for key, value in updates.items():
            if key not in CONFIG_SPEC:
                raise ValueError(f"Unknown parameter '{key}'. Allowed: {list(CONFIG_SPEC)}")
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise ValueError(f"Parameter '{key}' must be a number")
            lo, hi, _ = CONFIG_SPEC[key]
            if not math.isfinite(value) or not lo <= value <= hi:
                raise ValueError(f"Parameter '{key}' must be between {lo} and {hi}")
            clean[key] = float(value)
        with self._lock:
            self.config.update(clean)
            self.config_version += 1
            if clean:
                self.log(f"Config changed: {clean}", source="config")
            self._touch()

    # ------------------------------------------------------------------
    # Command queue (dashboard -> main loop)
    # ------------------------------------------------------------------
    def push_command(self, command: str, payload: dict | None = None):
        if command not in COMMANDS:
            raise ValueError(f"Unknown command '{command}'")
        self._commands.put({"command": command, "payload": payload or {},
                            "time": time.time()})
        self.log(f"Command queued: {command}", source="dashboard")

    def pop_commands(self) -> list:
        """Return (and remove) all queued commands. Call from the main loop."""
        out = []
        while True:
            try:
                out.append(self._commands.get_nowait())
            except queue.Empty:
                return out

    # ------------------------------------------------------------------
    # Snapshots (JSON-safe)
    # ------------------------------------------------------------------
    def _status_snapshot(self) -> dict:
        status = dict(self._status)
        start, end = status["started_at"], status["finished_at"]
        status["elapsed_s"] = ((end or time.time()) - start) if start else 0.0
        return status

    def section(self, name: str) -> dict:
        """JSON-safe copy of one section."""
        with self._lock:
            if name == "status":
                data = self._status_snapshot()
            elif name == "patient":
                data = dataclasses.asdict(self.patient)
            elif name in ("robot", "vision", "safety", "performance"):
                data = getattr(self, name)
            else:
                raise KeyError(name)
            return to_jsonable(data)

    def snapshot(self, include_logs: bool = True, log_limit: int = 50) -> dict:
        with self._lock:
            data = {
                "version": self.version,
                "timestamp": time.time(),
                "status": self._status_snapshot(),
                "patient": dataclasses.asdict(self.patient),
                "robot": self.robot,
                "vision": self.vision,
                "safety": self.safety,
                "performance": self.performance,
                "config": self.config,
            }
            if include_logs:
                data["logs"] = list(self.logs)[-log_limit:]
            return to_jsonable(data)